CREATE TABLE IF NOT EXISTS `audit_logs` (
  `id` CHAR(32) NOT NULL,
  `app` VARCHAR(32) NOT NULL DEFAULT '' COMMENT '所属应用，如 iot',
  `trace_id` VARCHAR(64) NOT NULL DEFAULT '',
  `user_id` VARCHAR(32) NOT NULL DEFAULT '',
  `user_name` VARCHAR(64) NOT NULL DEFAULT '',
  `operation_type` VARCHAR(16) NOT NULL DEFAULT '' COMMENT 'LOGIN/LOGOUT/CREATE/UPDATE/DELETE/QUERY',
  `operation_desc` VARCHAR(128) NOT NULL DEFAULT '',
  `method` VARCHAR(16) NOT NULL,
  `path` VARCHAR(255) NOT NULL,
  `query` VARCHAR(1024) NOT NULL DEFAULT '',
  `ip` VARCHAR(64) NOT NULL DEFAULT '',
  `user_agent` VARCHAR(512) NOT NULL DEFAULT '',
  `request_body` MEDIUMTEXT NULL,
  `response_body` MEDIUMTEXT NULL,
  `status` INT NOT NULL DEFAULT 0 COMMENT 'HTTP status',
  `result_code` INT NOT NULL DEFAULT 0 COMMENT '业务 code',
  `error_msg` VARCHAR(512) NOT NULL DEFAULT '',
  `duration_ms` BIGINT NOT NULL DEFAULT 0,
  `created_time` DATETIME NOT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_audit_app` (`app`),
  KEY `idx_audit_user` (`user_id`),
  KEY `idx_audit_created` (`created_time`),
  KEY `idx_audit_path` (`path`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='审计日志';
