CREATE TABLE IF NOT EXISTS `users` (
  `id` CHAR(32) NOT NULL COMMENT 'ULID',
  `version` BIGINT NOT NULL DEFAULT 0 COMMENT '乐观锁版本号',
  `user_name` VARCHAR(64) NOT NULL COMMENT '用户名',
  `password` VARCHAR(100) NOT NULL COMMENT 'bcrypt 哈希',
  `user_no` VARCHAR(64) NOT NULL COMMENT '员工号',
  `nick_name` VARCHAR(64) NOT NULL COMMENT '姓名',
  `birth_date` DATE NULL COMMENT '出生日期',
  `gender` VARCHAR(16) NOT NULL DEFAULT '' COMMENT '性别 male/female',
  `mail` VARCHAR(128) NOT NULL DEFAULT '' COMMENT '邮箱',
  `phone` VARCHAR(32) NOT NULL DEFAULT '' COMMENT '电话',
  `note` VARCHAR(255) NOT NULL DEFAULT '' COMMENT '备注',
  `auth_key` VARCHAR(128) NOT NULL DEFAULT '' COMMENT '认证密钥',
  `auth_mode` VARCHAR(16) NOT NULL DEFAULT 'local' COMMENT '认证模式 local/ldap/radius',
  `last_login_time` DATETIME NULL COMMENT '最后登录时间',
  `login_failure_times` INT NOT NULL DEFAULT 0 COMMENT '登录失败次数',
  `locked_until` DATETIME NULL COMMENT '锁定截止时间',
  `expire_times` INT NOT NULL DEFAULT 0 COMMENT '过期时间(分钟)',
  `status` VARCHAR(16) NOT NULL DEFAULT 'enabled' COMMENT '状态 enabled/disabled',
  `created_user` VARCHAR(64) NOT NULL DEFAULT '' COMMENT '创建人',
  `updated_user` VARCHAR(64) NOT NULL DEFAULT '' COMMENT '更新人',
  `created_time` DATETIME NOT NULL COMMENT '创建时间',
  `updated_time` DATETIME NOT NULL COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_users_user_name` (`user_name`),
  UNIQUE KEY `uk_users_user_no` (`user_no`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户';
